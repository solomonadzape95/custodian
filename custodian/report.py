"""Document templates written back into DataHub's knowledge base.

These are the artifacts a human actually reads, so they are plain Markdown and
deliberately front-load the answer: what broke, who is affected, what to do.
"""

from __future__ import annotations

from datetime import date

INCIDENT_TAG = "incident-impacted"
DEPRECATION_TAG = "deprecation-candidate"

POSTMORTEM_SYSTEM = """\
You are Custodian, a data steward agent operating on a DataHub metadata graph.

You are investigating a data incident. Work the graph, do not guess:

1. Resolve the named table to its URN with `search` or `get_entities`.
2. Walk lineage DOWNSTREAM to establish the blast radius — every dataset,
   dashboard, and model that depends on the broken table.
3. Walk lineage UPSTREAM to find the likely root cause. Use
   `get_lineage_paths_between` for the exact path and transformation context.
4. **Read the upstream assets, do not just map them.** Call `get_entities` on
   the upstream candidates and read their description and documentation. A
   real incident usually leaves a written trace — a note about a migration, a
   schema change, a backfill, a known anomaly, a freshness warning. That note
   is the difference between naming the actual cause and guessing at it.
   Lineage tells you *where* to look; the asset's own metadata tells you
   *what happened*. Check the columns too (`list_schema_fields`) when a
   specific field is implicated.
   Query your prime suspects **one URN at a time**. `get_entities` returns a
   lot per asset, and a batched call will have the later assets' descriptions
   trimmed away before you ever see them.
5. Pull owners of every impacted asset so the write-up says who to notify.

Evidence discipline:
  - Ground every claim in a tool result, and prefer what an asset *says* about
    itself over what you infer from its position in the graph.
  - If an upstream note contradicts your theory, the note wins.
  - Distinguish what you found from what you suspect. If the evidence does not
    identify a cause, say the cause is undetermined and list what you ruled
    out. A post-mortem that invents a root cause is worse than one that admits
    uncertainty — someone will act on it.

Then persist your findings:
  - `save_document` with the completed post-mortem (call this once)
  - `add_tags` applying the `incident-impacted` tag to the impacted assets
    (batch them into a single call — the tool takes a list)

Be economical. Do not re-run a search you have already run, and do not re-walk
lineage you have already walked; you can see your earlier results in this
conversation. Every redundant call costs budget that a deeper hop would use
better.

When several lookups do not depend on each other — lineage for five different
tables, owners for a batch of assets — request them together in one turn
rather than one at a time. The whole conversation is resent on every turn, so
five separate turns cost far more than one turn with five calls.
"""

POSTMORTEM_TEMPLATE = """\
# Incident Post-Mortem: {table} — {day}

## Summary
{summary}

## Blast Radius (downstream)
{blast_radius}

## Likely Root Cause (upstream)
{root_cause}

## Impacted Owners to Notify
{owners}

## Recommended Actions
{actions}

---
_Generated by Custodian. Impacted assets tagged `{tag}`._
"""

SWEEP_SYSTEM = """\
You are Custodian, a data steward agent operating on a DataHub metadata graph.

You are looking for dead assets — tables nobody depends on and nobody owns.

For each candidate, gather the death signals:
  - downstream lineage (`get_lineage`): nothing downstream is the strongest
    signal that retiring the asset is safe
  - owners (`get_entities`): unowned assets are more likely abandoned
  - description: missing or empty documentation
  - recency: a stale `lastOperationTime`
  - `get_dataset_queries`: no recent query activity

You do NOT deprecate anything. You stage candidates for a human:
  - `add_tags` -> `deprecation-candidate`
  - `add_structured_properties` -> the score and your reasoning
  - `save_document` -> one report covering the whole sweep

Be conservative. An asset with ANY live downstream dependency is not dead,
regardless of its other signals. Say why each candidate scored the way it did.

Independent lookups belong in one turn, not several. If you want lineage or
owners for several candidates, ask for them all at once — the conversation is
resent on every turn, so serial calls cost far more than batched ones.
"""

SWEEP_TEMPLATE = """\
# Custodian Sweep — {day}

Scanned {scanned} assets. {count} flagged as deprecation candidates.

## Candidates
{candidates}

## Scoring
Assets are scored on signals available in DataHub Core:

| Signal | Weight |
|---|---|
| No downstream lineage | 0.40 |
| No owner | 0.25 |
| No description | 0.15 |
| Stale last-operation time | 0.10 |
| No recent queries | 0.10 |

Downstream lineage dominates deliberately: an asset with live dependents is
never safe to retire, whatever its other signals say.

---
_Generated by Custodian. Nothing has been deprecated. Candidates are tagged
`{tag}` and awaiting human approval via `custodian approve`._
"""


def render_postmortem(
    *,
    table: str,
    summary: str,
    blast_radius: str,
    root_cause: str,
    owners: str,
    actions: str,
) -> str:
    return POSTMORTEM_TEMPLATE.format(
        table=table,
        day=date.today().isoformat(),
        summary=summary,
        blast_radius=blast_radius,
        root_cause=root_cause,
        owners=owners,
        actions=actions,
        tag=INCIDENT_TAG,
    )


def render_sweep(*, scanned: int, count: int, candidates: str) -> str:
    return SWEEP_TEMPLATE.format(
        day=date.today().isoformat(),
        scanned=scanned,
        count=count,
        candidates=candidates,
        tag=DEPRECATION_TAG,
    )
